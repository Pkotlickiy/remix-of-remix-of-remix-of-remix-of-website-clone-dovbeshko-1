export async function generateMetadata({ params }: { params: Promise<{ slug: string }> }): Promise<Metadata> {
  const { slug } = await params;
  const post = BLOG_POSTS[slug];

  if (!post) {
    return {
      title: "Статья не найдена",
    };
  }

  return {
    title: post.title,
    description: post.content.intro,
    keywords: [post.category, "юридическая консультация", "адвокат спб", "правовая помощь"],
    openGraph: {
      title: post.title,
      description: post.content.intro,
      url: `https://advokat-dovbeshko.ru/blog/${slug}`,
      type: "article",
      publishedTime: post.date,
      authors: ["Довбешко Светлана Юрьевна"],
    },
    alternates: {
      canonical: `/blog/${slug}`,
    },
  };
}

